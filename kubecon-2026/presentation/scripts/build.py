"""Build the public deck without the private rehearsal notes.

Run from anywhere: python3 kubecon-2026/presentation/scripts/build.py
"""
import base64
import re
from pathlib import Path

DECK = Path(__file__).resolve().parents[1]
def main():
    slides = (DECK / 'content' / 'slides.md').read_text()
    out = re.sub(r'^Notes:.*?(?=^---\s*$|\Z)', '', slides, flags=re.M | re.S)
    header = '<!-- Generated by scripts/build.py from slides.md. -->\n\n'
    (DECK / 'content' / 'talk.md').write_text(header + out)
    print('wrote content/talk.md:', out.count('\n---\n') + 1, 'slides')
    write_standalone(out)


def data_uri(path, mime):
    return f'data:{mime};base64,' + base64.b64encode(path.read_bytes()).decode()


def write_standalone(markdown):
    """deck.html: a standalone file with fonts, SVG and the QR code inlined."""
    def svg(match):
        text = (DECK / match.group(1)).read_text()
        return '<div class="figure">' + '\n'.join(l for l in text.splitlines() if l.strip()) + '</div>'
    markdown = re.sub(r'<div class="figure" data-svg="([^"]+)"></div>', svg, markdown)
    markdown = markdown.replace('src="assets/feedback-qr.png"', f'src="{data_uri(DECK / "assets/feedback-qr.png", "image/png")}"')
    css = (DECK / 'css/theme.css').read_text()
    css = re.sub(r'url\("\.\./(vendor/fonts/[^"]+)"\)', lambda m: f'url("{data_uri(DECK / m.group(1), "font/woff2")}")', css)
    vendor = DECK / 'vendor/reveal'
    html = (DECK / 'index.html').read_text()
    html = html.replace('<link rel="stylesheet" href="vendor/reveal/reveal.css">', f'<style>{(vendor / "reveal.css").read_text()}</style>')
    html = html.replace('<link rel="stylesheet" href="css/theme.css">', f'<style>{css}</style>')
    for name in ('reveal.js', 'markdown.js', 'notes.js'):
        html = html.replace(f'<script src="vendor/reveal/{name}"></script>', f'<script>{(vendor / name).read_text()}</script>')
    html = html.replace('<script src="js/deck.js"></script>', f'<script>{(DECK / "js/deck.js").read_text()}</script>')
    section = re.search(r'<section data-markdown="content/talk.md"(.*?)></section>', html, re.S)
    html = html.replace(section.group(0),
                        f'<section data-markdown{section.group(1)}><script type="text/template">\n{markdown}\n</script></section>')
    (DECK / 'deck.html').write_text(html)
    print('wrote deck.html:', round(len(html) / 1024), 'KB')


if __name__ == '__main__':
    main()
